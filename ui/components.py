def render_ml_prediction_section(decision_result: DecisionSupportResult):
    """Render preserved frozen XGBoost statistical prediction and probability distribution."""
    st.markdown("### 📊 1. ML Prediction — Statistical Model Output")
    st.caption("Empirical statistical prediction generated by the frozen XGBoost classifier (Holdout ROC-AUC: 64.68%).")

    pred_class = decision_result.ml_prediction
    p_app = decision_result.approval_probability
    p_rej = decision_result.rejection_probability

    c1, c2, c3 = st.columns([1.5, 2, 2])
    with c1:
        if pred_class == "Approved":
            st.metric(label="Predicted Class", value="Approved (1)", delta="Empirical Fit: Approved", delta_color="normal")
        else:
            st.metric(label="Predicted Class", value="Rejected (0)", delta="Empirical Fit: Rejected", delta_color="inverse")

    with c2:
        st.metric(label="Posterior P(Approved)", value=f"{p_app * 100:.2f}%")
        st.progress(p_app)

    with c3:
        st.metric(label="Posterior P(Rejected)", value=f"{p_rej * 100:.2f}%")
        st.progress(p_rej)

    st.info("ℹ️ The ML prediction is an empirical statistical probability and is not itself a final banking decision.")


def render_xai_section(decision_result: DecisionSupportResult, audit_record: AuditTrailRecord):
    """Render SHAP and LIME local feature attribution tabs."""
    st.markdown("### 🧠 2. Explainable AI (XAI) — Attribution Analysis")
    st.caption("Mathematical explanations indicating which applicant attributes influenced the XGBoost prediction.")

    tab_shap, tab_lime = st.tabs(["🌳 SHAP Explanation (TreeSHAP)", "🍋 LIME Explanation (Local Surrogate)"])

    with tab_shap:
        st.markdown("#### **TreeSHAP Additive Feature Contributions**")
        c1, c2 = st.columns(2)
        with c1:
            st.markdown("**🟢 Factors Pushing Toward Approval:**")
            if audit_record.shap_top_positive:
                for factor in audit_record.shap_top_positive:
                    st.markdown(f'<div class="tag-positive">+ {factor}</div>', unsafe_allow_html=True)
            else:
                st.write("No major positive SHAP contributors detected.")
        with c2:
            st.markdown("**🔴 Factors Pushing Toward Rejection:**")
            if audit_record.shap_top_negative:
                for factor in audit_record.shap_top_negative:
                    st.markdown(f'<div class="tag-negative">- {factor}</div>', unsafe_allow_html=True)
            else:
                st.write("No major negative SHAP contributors detected.")

    with tab_lime:
        st.markdown("#### **LIME Local Linear Surrogate Weights**")
        c3, c4 = st.columns(2)
        with c3:
            st.markdown("**🟢 Supporting Features (LIME Weight > 0):**")
            if audit_record.lime_top_positive:
                for factor in audit_record.lime_top_positive:
                    st.markdown(f'<div class="tag-positive">+ {factor}</div>', unsafe_allow_html=True)
            else:
                st.write("No major supporting LIME factors detected.")
        with c4:
            st.markdown("**🔴 Opposing Risk Features (LIME Weight < 0):**")
            if audit_record.lime_top_negative:
                for factor in audit_record.lime_top_negative:
                    st.markdown(f'<div class="tag-negative">- {factor}</div>', unsafe_allow_html=True)
            else:
                st.write("No major opposing LIME factors detected.")

    st.caption("Note: SHAP and LIME feature attributions describe model scoring mechanics within this dataset; they do not establish real-world causality.")


def render_policy_rag_section(decision_result: DecisionSupportResult, audit_record: AuditTrailRecord):
    """Render Policy RAG retrieval evidence or the zero-policy audit notice."""
    st.markdown("### 📜 3. Policy Verification & Regulatory Evidence (RAG)")
    st.caption("Institutional credit guidelines retrieved from the ChromaDB vector database based on applicant profile.")

    # Check if policy documents are active or zero
    if decision_result.policy_status == PolicyStatus.NO_POLICY_AVAILABLE:
        st.warning("⚠️ **Policy Verification: Not Available**")
        st.markdown(
            "> *No real bank policy documents have been supplied. Policy-grounded verification cannot be completed.*"
        )
        st.caption("The system maintains policy neutrality and will not invent or hardcode simulated lending rules.")
    else:
        st.success(f"✅ **Policy Knowledge Base Active** — Retrieved {len(decision_result.evidence_citations)} relevant clauses.")
        for idx, citation in enumerate(decision_result.evidence_citations, 1):
            page_str = f"Page {citation.page_number}" if citation.page_number != -1 else "N/A"
            with st.expander(f"📄 Evidence Clause {idx}: {citation.document_name} ({page_str}) — Score: {citation.relevance_score:.4f}"):
                st.markdown(f"**Chunk ID:** `{citation.chunk_id}`")
                st.markdown(f"**Excerpt:**\n> {citation.clause_snippet}")


def render_decision_agent_section(decision_result: DecisionSupportResult):
    """Render the Central AI Decision Agent recommendation, policy findings, and reasoning summary."""
    st.markdown("### 🤖 4. Central AI Decision-Support Recommendation")
    st.caption("Multimodal synthesis produced by the Central Policy-Aware AI Agent (Groq LLM).")

    rec = decision_result.final_recommendation
    status = decision_result.policy_status

    col_rec, col_status = st.columns([1.5, 1.5])
    with col_rec:
        st.markdown("**AI Decision-Support Recommendation:**")
        if rec == DecisionRecommendation.APPROVE_SUPPORT:
            st.markdown('<div class="badge-approve">✅ APPROVE_SUPPORT</div>', unsafe_allow_html=True)
        elif rec == DecisionRecommendation.REJECT_SUPPORT:
            st.markdown('<div class="badge-reject">❌ REJECT_SUPPORT</div>', unsafe_allow_html=True)
        elif rec == DecisionRecommendation.MANUAL_REVIEW:
            st.markdown('<div class="badge-manual">⚠️ MANUAL_REVIEW</div>', unsafe_allow_html=True)
        else:
            st.markdown('<div class="badge-info">ℹ️ INSUFFICIENT_INFORMATION</div>', unsafe_allow_html=True)

    with col_status:
        st.markdown("**Policy Compliance Assessment:**")
        if status == PolicyStatus.POLICY_SUPPORTED:
            st.markdown("`POLICY_SUPPORTED` — Satisfies retrieved guidelines.")
        elif status == PolicyStatus.POLICY_CONFLICT:
            st.markdown("`POLICY_CONFLICT` — Discrepancies detected.")
        elif status == PolicyStatus.INSUFFICIENT_POLICY_EVIDENCE:
            st.markdown("`INSUFFICIENT_POLICY_EVIDENCE` — Ambiguous evidence.")
        else:
            st.markdown("`NO_POLICY_AVAILABLE` — Policy repository empty.")

    st.markdown("#### **Agent Reasoning Summary:**")
    st.write(decision_result.reasoning_summary)

    # Key Findings & Discrepancies
    if decision_result.policy_findings or decision_result.policy_conflicts:
        c1, c2 = st.columns(2)
        with c1:
            if decision_result.policy_findings:
                st.markdown("**Policy Findings:**")
                for item in decision_result.policy_findings:
                    st.markdown(f"- {item}")
        with c2:
            if decision_result.policy_conflicts:
                st.markdown("**Policy Discrepancies / Risk Warnings:**")
                for item in decision_result.policy_conflicts:
                    st.markdown(f"- ⚠️ {item}")


